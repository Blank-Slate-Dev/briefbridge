-- ---------------------------------------------------------------------------
-- 5. handle_new_user() function + trigger
-- ---------------------------------------------------------------------------
--
-- When Supabase Auth creates a new user (via password sign-up OR OAuth),
-- the BEFORE-INSERT row hits auth.users. This trigger fires AFTER that insert
-- and creates the matching row in public.profiles. No app-layer code needed.
--
-- SECURITY DEFINER is essential: the function runs with the privileges of the
-- function's owner (postgres), not the caller (Supabase Auth's internal user).
-- Without SECURITY DEFINER, the trigger would fail with permission errors
-- because Supabase Auth doesn't have INSERT on public.profiles.
--
-- `set search_path = public` is a hardening measure: SECURITY DEFINER functions
-- should always pin their search_path to prevent search-path injection attacks.
--
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id) VALUES (NEW.id);
  RETURN NEW;
END;
$$;
--> statement-breakpoint

CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
--> statement-breakpoint

-- ---------------------------------------------------------------------------
-- 6. Row Level Security (defense-in-depth backstop)
-- ---------------------------------------------------------------------------
--
-- IMPORTANT context, repeated here because it's critical:
--
-- Drizzle connects as the `postgres` role (Supabase's transaction pooler
-- credentials), which BYPASSES RLS. So in normal operation, our explicit
-- `WHERE user_id = $userId` filters in the Drizzle queries are what enforce
-- access control.
--
-- These RLS policies are a SAFETY NET. If a query somewhere forgets a
-- user_id filter, AND that query runs as a Supabase-authenticated client
-- (i.e. via supabase-js with the user's JWT), RLS prevents data leakage.
--
-- We enable RLS even though our path doesn't use it day-to-day because:
--   1. We may add browser-side Supabase queries later (e.g. realtime
--      subscriptions). Those WILL respect RLS.
--   2. Supabase shows "RLS disabled" warnings in the dashboard for tables
--      without it, and we don't want to teach ourselves to ignore them.
--   3. Defense in depth costs nothing here.
--
-- The policies use auth.uid() — a Supabase-provided function that returns
-- the authenticated user's UUID, or NULL if unauthenticated. Coupled with
-- USING / WITH CHECK clauses, this is the standard Supabase RLS pattern.
--

ALTER TABLE "profiles" ENABLE ROW LEVEL SECURITY;
