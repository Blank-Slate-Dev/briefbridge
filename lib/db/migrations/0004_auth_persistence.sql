-- ---------------------------------------------------------------------------
-- 4. messages
-- ---------------------------------------------------------------------------
--
-- One row per chat message. Belongs to exactly one conversation.
-- Role is text + CHECK (not enum) to stay consistent with status above.
--
-- citations is JSONB and stores the FULL hit shape from semanticSearch():
--   [{ index, judgmentId, caseName, citation, paragraphNumber, paragraphText, similarity }, ...]
--
-- This is intentional — see the README's "Why store full citations" section.
-- TL;DR: snapshot semantics. If a judgment is amended later, the lawyer's
-- past research note still shows what was true at the time it was written.
--
-- No user_id column here — access is mediated entirely through the
-- conversation's user_id, which the RLS policy enforces. This is cleaner
-- than denormalising user_id onto every message.
--
CREATE TABLE "messages" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "conversation_id" uuid NOT NULL REFERENCES "conversations"(id) ON DELETE CASCADE,
  "role" text NOT NULL CHECK (role IN ('user', 'assistant')),
  "content" text NOT NULL,
  "citations" jsonb,
  "created_at" timestamp with time zone NOT NULL DEFAULT now()
);
