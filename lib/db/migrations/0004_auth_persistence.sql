-- Messages: access inherited from the parent conversation. A user can read,
-- write, modify, or delete a message IFF the parent conversation belongs to
-- them. This is enforced via EXISTS subquery, which uses the messages_
-- conversation_id_idx index for fast lookup.
ALTER TABLE "messages" ENABLE ROW LEVEL SECURITY;
--> statement-breakpoint
CREATE POLICY "messages_select_via_conversation" ON "messages"
  FOR SELECT USING (
    EXISTS (
      SELECT 1 FROM "conversations"
      WHERE "conversations"."id" = "messages"."conversation_id"
        AND "conversations"."user_id" = auth.uid()
    )
  );
--> statement-breakpoint
CREATE POLICY "messages_insert_via_conversation" ON "messages"
  FOR INSERT WITH CHECK (
    EXISTS (
      SELECT 1 FROM "conversations"
      WHERE "conversations"."id" = "messages"."conversation_id"
        AND "conversations"."user_id" = auth.uid()
    )
  );
--> statement-breakpoint
