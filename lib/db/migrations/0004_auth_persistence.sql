-- ---------------------------------------------------------------------------
-- 3. conversations
-- ---------------------------------------------------------------------------
--
-- One row per chat thread. matter_id is NULLABLE:
--   - NULL          → standalone /chat conversation, lives at /chat?conversationId=...
--   - non-NULL      → conversation belongs to a matter, shown inside the matter workspace
--
-- ON DELETE CASCADE on matter_id: if a matter is hard-deleted, its conversations go too.
-- (We don't hard-delete matters via the UI — that's CASCADE behaviour for safety,
-- not the default UX path.)
--
-- We also have user_id directly here (not just via matter_id) because:
--   - Standalone conversations have no matter
--   - Direct user_id makes RLS policies simpler and faster
--   - Faster "show me all this user's recent conversations" queries
--
CREATE TABLE "conversations" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "user_id" uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  "matter_id" uuid REFERENCES "matters"(id) ON DELETE CASCADE,
  "title" text,
  "created_at" timestamp with time zone NOT NULL DEFAULT now(),
  "updated_at" timestamp with time zone NOT NULL DEFAULT now()
);
