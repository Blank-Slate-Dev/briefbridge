-- ---------------------------------------------------------------------------
-- 1. profiles
-- ---------------------------------------------------------------------------
--
-- One row per user. The id IS the auth.users(id) — same UUID, propagated via
-- the handle_new_user() trigger. ON DELETE CASCADE means if Supabase deletes
-- an auth.users row (rare, but possible), the profile and all downstream
-- data cascades away cleanly.
--
-- Why not just read from auth.users directly?
--   - auth.users is owned by Supabase; we shouldn't extend it.
--   - We want app-specific fields (firm_name, role) that don't belong there.
--   - It cleanly separates "identity" (auth.users) from "profile" (public.profiles).
--
-- The trigger that populates this is defined below.
--
CREATE TABLE "profiles" (
  "id" uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  "full_name" text,
  "firm_name" text,
  "role" text,
  "created_at" timestamp with time zone NOT NULL DEFAULT now(),
  "updated_at" timestamp with time zone NOT NULL DEFAULT now()
);
